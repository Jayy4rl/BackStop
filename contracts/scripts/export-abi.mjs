// Writes the escrow ABIs from forge's build output into the shared package, so off-chain code
// always matches the compiled contracts. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pick = (file, name) => JSON.parse(readFileSync(join(root, 'out', file, `${name}.json`), 'utf8'));
const items = [
  ['escrowFactoryAbi', 'EscrowFactory.sol', 'EscrowFactory'],
  ['escrowAbi', 'Escrow.sol', 'Escrow'],
];
let out = '// Generated by contracts/scripts/export-abi.mjs from forge build output. Do not edit.\n\n';
for (const [ident, file, name] of items) {
  out += `export const ${ident} = ${JSON.stringify(pick(file, name).abi, null, 2)} as const;\n\n`;
}
const bytecode = (file, name) => pick(file, name).bytecode.object;
out += `/** Creation bytecode, used by local end-to-end tests that deploy on anvil. */\n`;
out += `export const escrowFactoryBytecode = '${bytecode('EscrowFactory.sol', 'EscrowFactory')}' as const;\n`;
out += `export const escrowImplementationBytecode = '${bytecode('Escrow.sol', 'Escrow')}' as const;\n`;
writeFileSync(join(root, '..', 'packages', 'shared', 'src', 'abi.generated.ts'), out);

// Test-only artifacts (mock USDC with an issuer blacklist, and the USDC freeze adapter) for
// end-to-end tests on a local chain. Not exported from the package index.
let t = '// Generated by contracts/scripts/export-abi.mjs. Test-only artifacts. Do not edit.\n\n';
for (const [ident, file, name] of [['mockUsdc', 'MockTokens.sol', 'MockUSDC'], ['usdcFreezeAdapter', 'FreezeAdapters.sol', 'UsdcFreezeAdapter']]) {
  const a = pick(file, name);
  t += `export const ${ident}Abi = ${JSON.stringify(a.abi)} as const;\n`;
  t += `export const ${ident}Bytecode = '${a.bytecode.object}' as const;\n\n`;
}
writeFileSync(join(root, '..', 'packages', 'shared', 'src', 'testing.generated.ts'), t);
console.log('wrote packages/shared/src/abi.generated.ts and testing.generated.ts');
